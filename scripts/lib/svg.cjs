const fs = require('node:fs');
const path = require('node:path');
const { Glyphs } = require('./text.cjs');

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

class SVG {
  constructor(w, h, title, desc = '') {
    Object.assign(this, { w, h, title, desc, parts: [], defs: [] });
    this.g = new Glyphs();
  }
  add(...s) { this.parts.push(...s); return this; }
  def(s) { this.defs.push(s); return this; }
  text(...a) { return this.g.text(...a); }
  measure(...a) { return this.g.measure(...a); }
  wrap(...a) { return this.g.wrap(...a); }
  finish() {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${this.w}" height="${this.h}" viewBox="0 0 ${this.w} ${this.h}" role="img" aria-labelledby="t d">`
      + `<title id="t">${esc(this.title)}</title><desc id="d">${esc(this.desc)}</desc>`
      + `<!-- Generated by scripts/build.cjs. Montserrat + JetBrains Mono (OFL) as outlines; icons from Simple Icons (CC0). Edit the generator, not this file. -->`
      + `<defs>${this.g.defsMarkup()}${this.defs.join('')}</defs>${this.parts.join('')}</svg>\n`;
  }
}

// Simple Icons path (24x24 viewBox) by slug
const iconCache = {};
function icon(slug) {
  if (!(slug in iconCache)) {
    const file = path.join(__dirname, '..', '..', 'node_modules', 'simple-icons', 'icons', `${slug}.svg`);
    iconCache[slug] = fs.readFileSync(file, 'utf8').match(/ d="([^"]+)"/)[1];
  }
  return iconCache[slug];
}
// draw a 24-unit icon path at x,y with size px
const drawIcon = (d, x, y, size, fill) =>
  `<path transform="translate(${x} ${y}) scale(${+(size / 24).toFixed(4)})" fill="${fill}" d="${d}"/>`;

// SMIL helpers. `still` builds omit them entirely so reduced-motion users get a calm final frame.
const fadeIn = (begin = 0, dur = 0.6) =>
  `<animate attributeName="opacity" values="0;1" dur="${dur}s" begin="${begin}s" fill="freeze" calcMode="spline" keyTimes="0;1" keySplines=".2 .7 .2 1"/>`;

// A typed line: clip grows glyph by glyph, then holds, then resets. Returns { clipDef, caretX animation }.
// x0: start x, width: full text width, steps: number of characters
function typing(id, x0, y, h, width, steps, { dur = 6, hold = 0.55, begin = 0 } = {}) {
  const typeEnd = Math.min(0.45, steps * 0.05 / dur * 1.4);
  const vals = [], keys = [];
  for (let i = 0; i <= steps; i++) { vals.push(+(width * i / steps).toFixed(1)); keys.push(+(typeEnd * i / steps).toFixed(4)); }
  vals.push(width, 0); keys.push(+(typeEnd + hold).toFixed(4) > .98 ? .98 : +(typeEnd + hold).toFixed(4), 1);
  const anim = attr => `<animate attributeName="${attr}" values="${vals.join(';')}" keyTimes="${keys.join(';')}" dur="${dur}s" begin="${begin}s" calcMode="discrete" repeatCount="indefinite"/>`;
  const clip = `<clipPath id="${id}"><rect x="${x0}" y="${y}" width="${width}" height="${h}">${anim('width')}</rect></clipPath>`;
  const caret = (cx, cy, cw, ch, fill) =>
    `<rect x="${x0 + width + 2}" y="${cy}" width="${cw}" height="${ch}" fill="${fill}">`
    + `<animate attributeName="x" values="${vals.map(v => +(x0 + v + 2).toFixed(1)).join(';')}" keyTimes="${keys.join(';')}" dur="${dur}s" begin="${begin}s" calcMode="discrete" repeatCount="indefinite"/>`
    + `<animate attributeName="opacity" values="1;0;1" dur="1s" calcMode="discrete" keyTimes="0;.5;1" repeatCount="indefinite"/></rect>`;
  return { clip, caret };
}

module.exports = { SVG, esc, icon, drawIcon, fadeIn, typing };
